# ---------- Lowara e-SH ----------
pumps = []
group_q, rpm = None, None
for line in open(os.path.join(S, 'pumps_raw.txt'), encoding='utf-8'):
    line = line.strip()
    if not line:
        continue
    if line.startswith('#GROUP'):
        _, rpm, qs = line.split()
        rpm = int(rpm)
        group_q = [float(x) for x in qs.split(',')]
        continue
    name, kw, imp, full, eta, hs = line.split('|')
    hv = hs.split(',')
    assert len(hv) == len(group_q), name
    q, h = [], []
    for qq, hh in zip(group_q, hv):
        if hh != '_':
            q.append(qq); h.append(float(hh))
    pumps.append({
        'brand': 'Lowara', 'model': 'e-SH ' + name, 'category': 'e-SH Santrifüj (EN 733, AISI 316)',
        'desc': f"{'2 kutuplu 2900' if rpm == 2900 else '4 kutuplu 1450'} d/d · Çark Ø{imp} mm ({'tam' if full == '1' else 'tıraşlı'})",
        'kw': float(kw), 'hp': round(float(kw) / 0.7457, 2), 'rpm': rpm, 'eta': float(eta),
        'volt': '3~ 400' if float(kw) > 2.2 else '1~230 / 3~400',
        'inlet': '', 'outlet': 'DN' + name.split('-')[0],
        'q_unit': 'm3/h', 'q': q, 'h': h, 'max_temp': '120°C', 'price': '', 'page': 29 if rpm == 2900 else 32,
        'source': 'eSH_50Hz_EN.pdf', 'image': 'esh_p05_x39.png'})
json.dump(pumps, open(os.path.join(D, 'lowara.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
print('lowara', len(pumps))

